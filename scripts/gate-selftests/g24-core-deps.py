# --- the committed fixture lock: tracked, not ignored, path-only ------------------------------
FIXTURE_LOCK_REL = "tests/g53-fixture/Cargo.lock"
PRE_FIX_IGNORE_RULE = "/tests/g53-fixture/Cargo.lock"   # the .gitignore line that kept the lock out of every clone


def lock_git_problems(repo: Path) -> list[str]:
    """What would keep the fixture lock out of a fresh clone of `repo`: it is not in the index (a clone
    never receives it), or an ignore rule matches it (`--no-index`, so a force-added lock that a rule
    still matches is reported too - the rule would drop it again on the next re-add). Fail-closed when
    git cannot answer."""
    def git(*args: str) -> int:
        return subprocess.run(["git", "-C", str(repo), *args], capture_output=True).returncode
    try:
        tracked = git("ls-files", "--error-unmatch", "--", FIXTURE_LOCK_REL)
        ignored = git("check-ignore", "-q", "--no-index", "--", FIXTURE_LOCK_REL)
    except OSError as exc:
        return [f"git could not be run ({exc}) - cannot prove the fixture lock is committed"]
    problems = []
    if tracked == 1:
        problems.append(f"{FIXTURE_LOCK_REL} is not tracked - a fresh clone has no fixture lock")
    elif tracked != 0:
        problems.append(f"`git ls-files` exited {tracked} - cannot prove the fixture lock is tracked")
    if ignored == 0:
        problems.append(f"{FIXTURE_LOCK_REL} matches an ignore rule")
    elif ignored != 1:
        problems.append(f"`git check-ignore` exited {ignored} - cannot prove the fixture lock is not ignored")
    return problems


def throwaway_repo(td: str, *, ignore_rule: bool, force_add: bool) -> Path:
    """A throwaway git repo holding a fixture lock at the real path, optionally under the pre-fix ignore
    rule and optionally force-added to the index."""
    repo = Path(td)
    subprocess.run(["git", "init", "-q", str(repo)], capture_output=True, check=True)
    lock = repo / FIXTURE_LOCK_REL
    lock.parent.mkdir(parents=True)
    lock.write_text("version = 4\n", encoding="utf-8", newline="\n")
    if ignore_rule:
        (repo / ".gitignore").write_text(PRE_FIX_IGNORE_RULE + "\n", encoding="utf-8", newline="\n")
    if force_add:
        subprocess.run(["git", "-C", str(repo), "add", "-f", "--", FIXTURE_LOCK_REL], capture_output=True, check=True)
    return repo


