# --- live: run the REAL fixture through `cargo metadata --locked` when cargo is installed (P1) --
def cargo_locked_metadata(manifest: Path) -> tuple[str, str]:
    """`cargo metadata --locked` over a fixture manifest -> ('ok', stdout) | ('stale', stderr) | ('env',
    stderr). `--locked` refuses to create or rewrite the lock, so a missing or stale committed lock is a
    verdict here, never a silent regeneration. The cwd is the repo root, so rustup resolves the pinned
    toolchain for a throwaway copy outside the tree as well."""
    proc = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--manifest-path", str(manifest)],
        cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.returncode == 0:
        return "ok", proc.stdout
    if "--locked was passed" in proc.stderr:     # cargo's refusal for both a stale and an absent lock
        return "stale", proc.stderr
    return "env", proc.stderr


