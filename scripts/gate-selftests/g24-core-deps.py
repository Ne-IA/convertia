    nodes[FLATE2_ID]["deps"] = [{"pkg": f"{d} 0.0.0"} for d in deps]
    nodes[FLATE2_ID]["features"] = list(activated)
    return {"packages": packages, "resolve": {"nodes": list(nodes.values())}}


